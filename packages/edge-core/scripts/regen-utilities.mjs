#!/usr/bin/env node
/**
 * Regenerate src/ssr/utilitiesCss.ts — the static Tailwind utility stylesheet
 * the eSSR landing components rely on (Navbar, Pricing, Footer, Hero, …).
 *
 * WHY: the community/worker render path (shell.ts) has no Tailwind runtime, so
 * it ships FALLBACK_CSS. The landing components emit Tailwind class names
 * (hidden md:flex, container mx-auto, bg-muted/50, …). Without these rules in
 * the page CSS, responsive behaviour breaks — e.g. desktop + mobile navbars
 * render at once. This script compiles exactly the utility classes the
 * component sources use and embeds them as a string constant appended to
 * FALLBACK_CSS, so the markup renders correctly with no runtime Tailwind.
 *
 * RUN: `node scripts/regen-utilities.mjs` from this package, then rebuild
 * (`pnpm --filter @frontbase/edge-core build`). Re-run whenever a landing
 * component introduces new Tailwind classes.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, globSync, unlinkSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, '..');
const config = join(here, 'utilities-tailwind.cjs');
const input = join(here, 'utilities-input.css');
const outTs = join(pkgRoot, 'src', 'ssr', 'utilitiesCss.ts');

// Locate the Tailwind v3 CLI. It is a transitive dep (via @frontbase/admin-console)
// in the pnpm store; resolve it robustly from the repo root upwards.
function findCli() {
    const patterns = [
        'node_modules/tailwindcss/lib/cli.js',
        'node_modules/.pnpm/tailwindcss@*/node_modules/tailwindcss/lib/cli.js',
    ];
    let dir = pkgRoot;
    while (dir !== dirname(dir)) {
        for (const p of patterns) {
            const full = join(dir, p);
            try {
                const hits = globSync(full);
                if (hits.length > 0) return hits[0];
            } catch { /* globSync throws on no-match in some Node versions */ }
        }
        dir = dirname(dir);
    }
    return null;
}

const cli = findCli();
if (!cli) {
    console.error('[regen-utilities] tailwindcss CLI not found. Install tailwindcss (v3) first.');
    process.exit(1);
}
if (!existsSync(input) || !existsSync(config)) {
    console.error('[regen-utilities] missing input/config sibling files.');
    process.exit(1);
}

const tmpOut = join(tmpdir(), `frontbase-utilities-${process.pid}.css`);
const result = spawnSync(process.execPath, [cli, '-c', config, '-i', input, '-o', tmpOut, '--minify'], {
    cwd: pkgRoot,
    encoding: 'utf8',
});
// Tailwind prints logs to stderr; surface them only on non-zero exit.
if (result.status !== 0) {
    console.error(result.stderr || result.stdout);
    console.error('[regen-utilities] Tailwind CLI failed.');
    process.exit(1);
}

const css = readFileSync(tmpOut, 'utf8').trim();
try { unlinkSync(tmpOut); } catch { /* best effort */ }
if (!css) {
    console.error('[regen-utilities] Tailwind produced empty output.');
    process.exit(1);
}

const banner = `/**
 * GENERATED by scripts/regen-utilities.mjs — DO NOT EDIT BY HAND.
 *
 * Static Tailwind utility stylesheet compiled from every eSSR component source
 * under src/ssr. Appended to FALLBACK_CSS so the landing components' class
 * names resolve on the community/worker render path (which has no Tailwind
 * runtime). Regenerate after changing a landing component's classes:
 *   node scripts/regen-utilities.mjs
 */
`;

writeFileSync(
    outTs,
    `${banner}export const UTILITIES_CSS = ${JSON.stringify(css)};\n`,
    'utf8',
);
console.log(`[regen-utilities] wrote ${outTs.replace(pkgRoot, '.')} (${css.length} bytes of utilities)`);
