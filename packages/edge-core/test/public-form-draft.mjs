import assert from 'node:assert/strict';
import { createPublicFormDraft, publicFormDraftSchema } from '../dist/index.js';
import { renderDataComponent } from '../dist/ssr/components/data.js';
const form = createPublicFormDraft();
const render = value => renderDataComponent('Form', 'application', { publicFormDraft: value }, '');
assert(publicFormDraftSchema.safeParse(form).success);
const html = render(form);
assert(html.includes('Preview only. Applications are not being collected.'));
assert(html.includes('type="email"'));
assert(html.includes('for="application-field-1"'));
assert(!/<form\b|data-react-component|data-fb-hydrate|action=|type="submit"/.test(html));
assert(html.includes('<fieldset disabled'));
assert(html.includes('type="button" disabled'));
assert(!publicFormDraftSchema.safeParse({ ...form, endpoint: 'https://evil.invalid' }).success);
assert(!publicFormDraftSchema.safeParse({ ...form, fields: [...form.fields, form.fields[0]] }).success);
assert(!publicFormDraftSchema.safeParse({ ...form, fields: Array.from({ length:25 }, (_,i) => ({ ...form.fields[0], name:`n${i}` })) }).success);
assert(!publicFormDraftSchema.safeParse({ ...form, fields:[{ ...form.fields[0], type:'file' }] }).success);
const escaped=render({ ...form, title:'<script>evil</script>', fields:[{name:'consent', label:'<img src=x onerror=evil()>', type:'consent', required:true}] });
assert(!escaped.includes('<script>') && !escaped.includes('<img'));
assert(escaped.includes('type="checkbox"') && escaped.includes(' required disabled'));
const invalid=render({ ...form, fields:[{ ...form.fields[0], name:'x" onfocus="evil' }] });
assert.equal(invalid, '<div role="status">Application form configuration needs review.</div>');
const legacy=renderDataComponent('Form', 'legacy', { title:'Database editor' }, '');
assert(legacy.includes('data-react-component="Form"') && !legacy.includes('public-form-draft'));
console.log('Public form draft: schema, escaping, inert authoring and legacy isolation PASS');
