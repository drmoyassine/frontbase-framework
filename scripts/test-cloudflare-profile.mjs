import assert from 'node:assert/strict';
import {defaultDeploymentManifest,managedRuntimeManifest,readManagedRuntimeManifest} from '../packages/edge-core/dist/deployment.js';
import {profileEnvironment} from './deployment-setup/profile-environment.mjs';
import {projectWorkerIdentity} from './deployment-setup/cloudflare-identity.mjs';
import {validateReceipt} from './deployment-setup/receipt.mjs';
import {reuseManifest,managedExecutionIssues} from './deployment-setup/cloudflare-lifecycle.mjs';
const id='11111111-2222-3333-4444-555555555555';
const context={accountId:'a'.repeat(32),appName:'profile-fixture',environment:'preview',artifactHash:'a'.repeat(64)};
const manifest=defaultDeploymentManifest('cloudflare');manifest.bindings.cache.mode='disabled';manifest.bindings.cache.config={};
manifest.bindings['state-db']={adapterId:'libsql-http',mode:'connect',config:{url:'https://state.example'},secretRefs:{token:'state/token'}};
manifest.bindings.vector={adapterId:'cloudflare-vectorize-http',mode:'connect',config:{accountId:context.accountId,indexName:'fixture'},secretRefs:{token:'vector/token'}};
const credentials={'state/token':'synthetic-state-private','vector/token':'synthetic-vector-private'};
const environment=profileEnvironment({manifest,credentials});
const runtime=managedRuntimeManifest(manifest,{});
assert.deepEqual(readManagedRuntimeManifest(runtime),runtime);
for(const value of Object.values(credentials))assert.ok(!JSON.stringify(runtime).includes(value));
assert.deepEqual(JSON.parse(environment.FRONTBASE_CACHE),{provider:'none'});
const receipt={schemaVersion:1,installationId:id,operationId:id,revision:0,...context,manifest,phase:'prepared',pending:null,resources:{},identity:null,url:null};
assert.equal(validateReceipt(receipt,context),receipt);
assert.deepEqual(reuseManifest(receipt),manifest);
assert.deepEqual(managedExecutionIssues(manifest,context,'redeploy',receipt),[]);
const changed=structuredClone(manifest);changed.bindings['state-db'].config.url='https://different.example';
assert.ok(managedExecutionIssues(changed,context,'redeploy',receipt).length);
const settings={bindings:[{name:'FRONTBASE_INSTALLATION_ID',type:'plain_text',text:id},{name:'FRONTBASE_DEPLOYMENT_MANIFEST',type:'plain_text',text:JSON.stringify(runtime)},...['SESSION_SECRET','APP_DB_URL','APP_DB_AUTH_TOKEN','FRONTBASE_VECTOR'].map(name=>({name,type:'secret_text'}))]};
const deployments=[{id,created_on:'2026-10-26T00:00:00Z',versions:[{version_id:id,percentage:100}]}];
assert.deepEqual(projectWorkerIdentity(settings,deployments,context).resources,{});
assert.throws(()=>projectWorkerIdentity({bindings:settings.bindings.filter(b=>b.name!=='APP_DB_AUTH_TOKEN')},deployments,context));
assert.throws(()=>projectWorkerIdentity({bindings:[...settings.bindings,{name:'DB',type:'d1',id}]},deployments,context));
console.log('PASS CF HTTP profiles: shared lowering, no secret values in metadata, exact receipt/redeploy and state-identity checks');
